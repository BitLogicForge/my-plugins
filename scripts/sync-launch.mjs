// Regenerates .vscode/launch.json from the folders in extensions/.
// Run after adding/removing an extension (new-extension.mjs calls it for you).
import { readdirSync, existsSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export function syncLaunch() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const extRoot = path.join(root, 'extensions');
  const names = existsSync(extRoot)
    ? readdirSync(extRoot, { withFileTypes: true })
        .filter((e) => e.isDirectory() && existsSync(path.join(extRoot, e.name, 'package.json')))
        .map((e) => e.name)
        .sort()
    : [];

  const devPath = (n) => `--extensionDevelopmentPath=\${workspaceFolder}/extensions/${n}`;
  const runConfig = (name, exts) => ({
    name,
    type: 'extensionHost',
    request: 'launch',
    args: ['--disable-extensions', ...exts.map(devPath)],
    outFiles: exts.map((n) => `\${workspaceFolder}/extensions/${n}/dist/**/*.js`),
    preLaunchTask: 'watch: all',
  });

  const configurations = [];
  if (names.length > 1) configurations.push(runConfig('Run: all extensions', names));
  for (const n of names) configurations.push(runConfig(`Run: ${n}`, [n]));
  const header =
    '// GENERATED by scripts/sync-launch.mjs from the folders in extensions/. Do not edit by hand;\n' +
    '// re-run `node scripts/sync-launch.mjs` instead.\n';
  mkdirSync(path.join(root, '.vscode'), { recursive: true });
  writeFileSync(
    path.join(root, '.vscode', 'launch.json'),
    header + JSON.stringify({ version: '0.2.0', configurations }, null, 2) + '\n',
  );
  return names;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log(`launch.json updated for: ${syncLaunch().join(', ') || '(none)'}`);
}
